    private void DrawPixelIcon(int glyph, Vector2 at, float scale, Color color)
    {
        glyph = Mathf.Clamp(glyph, 0, PixelGlyphs.Length - 1);
        // Cache by glyph and foreground color; no per-frame texture allocation.
        int key = glyph * 397 ^ ((Color32)color).GetHashCode();
        if (!pixelIcons.TryGetValue(key, out Texture2D texture))
        {
            string[] mask = PixelGlyphs[glyph];
            var pixels = new Color32[18 * 18];
            for (int y = 0; y < 16; y++)
                for (int x = 0; x < mask[y].Length; x++)
                    if (mask[y][x] != '.')
                        for (int dy = -1; dy <= 1; dy++)
                            for (int dx = -1; dx <= 1; dx++)
                                pixels[(16 - y + dy) * 18 + x + 1 + dx] = (Color32)PixelEdge;
            for (int y = 0; y < 16; y++)
                for (int x = 0; x < mask[y].Length; x++)
                {
                    char value = mask[y][x];
                    if (value == '.') continue;
                    Color c = value == '2' ? Hex("e9faff") : value == '3' ? Cyan : value == '4' ? Gold : color;
                    pixels[(16 - y) * 18 + x + 1] = (Color32)c;
                }
            texture = new Texture2D(18, 18, TextureFormat.RGBA32, false) { filterMode = FilterMode.Point, wrapMode = TextureWrapMode.Clamp };
            texture.SetPixels32(pixels); texture.Apply(false, true); pixelIcons.Add(key, texture);
        }
        GUI.DrawTexture(new Rect(Mathf.Round(at.x - scale * .5f), Mathf.Round(at.y - scale * .5f), scale * 9, scale * 9), texture, ScaleMode.StretchToFill, true);
    }
